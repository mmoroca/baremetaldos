#!/usr/bin/env python3
#
# Build and run the host test for the page-table walk in bare_dynarec.cpp.
#
# Usage:
#   make check-dynarec           # part of make check-host
#
"""
gen-dynarec.py - test the page-table walk of bare_dynarec.cpp on the host.

Why this exists: the walk in bare_dynarec.cpp is the one piece of this port that
can corrupt the machine silently.  It reads live page tables and writes one bit
into them, so a wrong index, a wrong mask or a wrong descriptor type check does
not fail loudly - it clears a PXN bit on the wrong 64 KB page, or follows a
pointer that is not one, and the next thing you see is a fault with no message.

None of that can be exercised by compiling: the real thing needs the MMU.  So
the arithmetic is extracted *verbatim* from the file, between two markers, and
run against page tables that this script builds to match Circle's layout
(lib/translationtable64.cpp: 64 KB granule, three levels, 1 GB / 2 MB / 64 KB).

What is checked, and each of these is a bug that would be invisible on the
board until much later:

  1. only the descriptors covering the range lose PXN, and the count is right;
  2. a range that starts and ends in the middle of a page still covers both;
  3. UXN and every other bit are left alone;
  4. a PXN bit that was already clear is not counted as changed;
  5. a descriptor that is not what the walk expects makes it give up, with -1,
     instead of writing through whatever pointer it found;
  6. the walk never writes outside the level 3 table it walked.

    make check-dynarec
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "src/platform/bare_dynarec.cpp"
OUT = ROOT / "scripts/hostcheck/dynarec_test.cpp"

text = SRC.read_text(encoding="utf-8")

START = "int ClearPXNForRange (u64 nStart, u64 nEnd)"
END = "} // namespace"

try:
    i = text.index(START)
    j = text.index(END, i)
except ValueError:
    sys.exit("gen-dynarec: no encuentro ClearPXNForRange en bare_dynarec.cpp "
             "(¿se ha movido o renombrado?)")

block = text[i:j]

HEAD = r'''// GENERATED by scripts/hostcheck/gen-dynarec.py - do not edit.
//
// Runs the real page-table walk from bare_dynarec.cpp against page tables built
// here in Circle's own layout.  See the generator's docstring for what each
// check is for.
#include <cstdio>
#include <cstring>

typedef unsigned long long u64;
typedef unsigned int u32;

// Circle's spelling, which the port uses inside this file.
typedef bool boolean;
#define TRUE  true
#define FALSE false

// --- the constants and the sysreg reads the block expects -------------------
static constexpr u64 PageSize = 0x10000;
static constexpr u64 DescTypeMask = 0x3;
static constexpr u64 DescTypeTable = 0x3;
static constexpr u64 DescTypePage = 0x3;
static constexpr u64 BitPXN = 1ULL << 53;
static constexpr u64 BitUXN = 1ULL << 54;	// Circle sets this on every page
static constexpr u64 BitAF = 1ULL << 10;
static constexpr u64 DescAddressMask = 0x0000FFFFFFFF0000ULL;

// The three calls into the machine.  TTBR0 points at the fake tables; the two
// barriers are no-ops here, which is correct: on the host they only order
// memory, and ordering is not what this test is about.
static u64 s_nFakeTtbr0 = 0;
static int s_nWarnings = 0;

static u64 ReadTtbr0 (void) { return s_nFakeTtbr0; }

// Unused by the block (it is called by the entry point, not by the walk), but
// defined so the file reads like the real one.  Referenced once to keep the
// compiler from saying so.
static void SyncInstructionStream (void) {}
static void (*const s_pSyncReference) (void) = &SyncInstructionStream;

// The two things the block says when it refuses to continue.  Logged, not
// printed: what the test checks is that it *stops*, and the messages would
// drown the results.
static const char FromDynarec[] = "dynarec";
enum { LogWarning = 3, LogError = 4, LogNotice = 2 };

class CLogger
{
public:
	static CLogger *Get (void) { static CLogger Logger; return &Logger; }
	void Write (const char *, int, const char *, ...) { s_nWarnings++; }
};

'''

TAIL = r'''
// ---------------------------------------------------------------------------
// Building a page table that looks like Circle's
// ---------------------------------------------------------------------------
//
// The layout, from lib/translationtable64.cpp and include/circle/armv8mmu.h:
//
//   TTBR0 -> level 1, 128 entries on a Pi 4, 512 MB each (LEVEL2_TABLE_ENTRIES;
//            the table itself is PAGE_SIZE, so 512 entries fit).  Each entry is
//            a *table* descriptor pointing straight at a page table.
//   level 3, 8192 entries of 64 KB, a page descriptor each, AF set, PXN = 1
//            above _etext - which is the case being undone.
//
// Note what is NOT here: a middle level.  Circle's 64 KB granule walk has two
// levels in use, and the first version of bare_dynarec.cpp assumed three -
// which this test caught, because with three it walked a table full of zeros
// and refused, and a walk that refuses is the safe failure.
//
// One level 1 and one page table, and every address the test uses is inside
// them - so a walk that reads or writes outside is caught by the canaries, not
// by luck.

alignas(0x10000) static u64 s_L1[512];

// Two page tables, because one is not enough to tell a correct walk from an
// incorrect one: everything inside the first 512 MB looks the same whether the
// first-level index is (addr >> 29) or (addr >> 30), and a test that cannot
// tell those two apart passed a deliberately broken walk while this file was
// being written.  Entry 0 covers 0..512 MB, entry 1 covers 512 MB..1 GB.
alignas(0x10000) static u64 s_L3[8192];		// first 512 MB
alignas(0x10000) static u64 s_L3B[8192];	// second 512 MB

// A canary either side of the level 3 table: a walk that writes 64 KB off the
// end of it is a corrupted page table and a fault much later.
static u64 s_Canary_Before[16];
static u64 s_Canary_After[16];

static void ResetTables (void)
{
	memset (s_L1, 0, sizeof s_L1);
	memset (s_L3, 0, sizeof s_L3);
	memset (s_Canary_Before, 0xAA, sizeof s_Canary_Before);
	memset (s_Canary_After, 0xBB, sizeof s_Canary_After);

	// Level 1 -> the page table, directly.  Entry 0 covers the first 512 MB,
	// which is where every address this test uses lives.
	s_L1[0] = DescTypeTable | ((u64) s_L3 & DescAddressMask);
	s_L1[1] = DescTypeTable | ((u64) s_L3B & DescAddressMask);

	// Every page in the table: valid, accessible, PXN set - i.e. what Circle
	// does above _etext.
	for (unsigned n = 0; n < 8192; n++)
	{
		s_L3[n] = DescTypePage
			| BitAF
			| BitPXN
			| BitUXN	// as Circle does: user execute never
			| (((u64) n * PageSize) & DescAddressMask);

		s_L3B[n] = s_L3[n] | (512ULL * 1024 * 1024 & DescAddressMask);
	}

	s_nFakeTtbr0 = (u64) s_L1;
}

// The address of page `n` in the fake layout.  Deliberately computed the same
// way the walk does it (index into the 64 KB page space of the first 512 MB),
// so a mistake in the test shows up as a failure rather than cancelling out.
static u64 PageAddress (unsigned n)
{
	return (u64) n * PageSize;
}

static int s_nChecks = 0;
static int s_nFailures = 0;

static void Check (bool bCondition, const char *pWhat)
{
	s_nChecks++;
	if (!bCondition)
	{
		s_nFailures++;
		printf ("  FALLO  %s\n", pWhat);
	}
	else
	{
		printf ("  ok     %s\n", pWhat);
	}
}

static unsigned PagesWithPXN (void)
{
	unsigned n = 0;
	for (unsigned i = 0; i < 8192; i++)
	{
		if ((s_L3[i] & BitPXN) != 0)
		{
			n++;
		}
		if ((s_L3B[i] & BitPXN) != 0)
		{
			n++;
		}
	}
	return n;
}

static unsigned PagesWithPXNA (void)
{
	unsigned n = 0;
	for (unsigned i = 0; i < 8192; i++)
	{
		if ((s_L3[i] & BitPXN) != 0)
		{
			n++;
		}
	}
	return n;
}

int main (void)
{
	printf ("dinarec: el recorrido de tablas de bare_dynarec.cpp\n\n");

	// --- 1. a 3-page range in the middle --------------------------------
	ResetTables ();
	{
		const u64 nStart = PageAddress (100) + 0x1234;	// not page aligned
		const u64 nEnd   = PageAddress (102) + 0x10;	// ends inside page 102
		const int n = ClearPXNForRange (nStart, nEnd);

		printf ("\n[1] rango de 3 paginas, sin alinear\n");
		Check (n == 3, "devuelve 3 paginas cambiadas");
		Check (PagesWithPXN () == 16384 - 3, "exactamente 3 pierden PXN");
		Check ((s_L3[100] & BitPXN) == 0, "la pagina 100 (la del inicio) tambien");
		Check ((s_L3[101] & BitPXN) == 0, "la pagina 101");
		Check ((s_L3[102] & BitPXN) == 0, "la pagina 102 (la del final)");
		Check ((s_L3[99]  & BitPXN) != 0, "la 99 no se toca");
		Check ((s_L3[103] & BitPXN) != 0, "la 103 no se toca");
	}

	// --- 2. nothing else in the descriptor moves ------------------------
	ResetTables ();
	{
		const u64 nBefore = s_L3[200];
		const int n = ClearPXNForRange (PageAddress (200), PageAddress (200) + 1);

		printf ("\n[2] solo cambia el bit PXN\n");
		Check (n == 1, "una pagina");
		Check ((s_L3[200] & ~BitPXN) == (nBefore & ~BitPXN),
		       "todos los demas bits del descriptor siguen igual");
		Check ((s_L3[200] & BitUXN) != 0, "UXN sigue a 1 (no se toca)");
		Check ((s_L3[200] & BitAF) != 0, "AF sigue a 1");
	}

	// --- 3. already executable: nothing to do, nothing counted ----------
	ResetTables ();
	{
		s_L3[300] &= ~BitPXN;
		const int n = ClearPXNForRange (PageAddress (300), PageAddress (300) + 1);

		printf ("\n[3] una pagina que ya era ejecutable\n");
		Check (n == 0, "no cuenta como cambio");
		Check ((s_L3[300] & BitPXN) == 0, "y sigue ejecutable");
	}

	// --- 4. a level 3 descriptor that is not a page ---------------------
	ResetTables ();
	{
		s_L3[400] = 0;			// invalid descriptor
		const int n = ClearPXNForRange (PageAddress (400), PageAddress (401));

		printf ("\n[4] descriptor invalido en medio del rango\n");
		Check (n < 0, "se rinde con -1 en vez de escribir");
		Check ((s_L3[400] & DescTypeMask) == 0, "y no lo toca");
	}

	// --- 5. a level 2 entry that is not a table -------------------------
	ResetTables ();
	{
		s_L1[0] = 0;			// as if the first 512 MB were unmapped
		const int n = ClearPXNForRange (PageAddress (500), PageAddress (500) + 1);

		printf ("\n[5] entrada de nivel 1 que no es tabla\n");
		Check (n < 0, "se rinde con -1");
		Check (PagesWithPXN () == 16384, "no cambia ninguna pagina");
	}

	// --- 6. a whole 8 MB cache, as the real call does -------------------
	ResetTables ();
	{
		const u64 nStart = PageAddress (128);		// 8 MB = 128 pages
		const u64 nEnd   = nStart + 8 * 1024 * 1024;
		const int n = ClearPXNForRange (nStart, nEnd);

		printf ("\n[6] los 8 MB de la cache del dynarec\n");
		Check (n == 128, "128 paginas de 64 KB");
		Check (PagesWithPXN () == 16384 - 128, "y ninguna mas");
		Check ((s_L3[127] & BitPXN) != 0, "la de antes del bloque no se toca");
		Check ((s_L3[255] & BitPXN) == 0, "la ultima del bloque si (128..255)");
		Check ((s_L3[256] & BitPXN) != 0, "la de despues tampoco");
	}

	// --- 7. the second 512 MB: what tells >> 29 from >> 30 -------------
	// Everything in the first half gigabyte exercises index 0 whether the
	// first-level index is computed with a 512 MB or a 1 GB shift, so it is
	// this case, and only this one, that catches the difference.  (It is here
	// because the first version of this test did not have it and happily
	// passed a walk that had been broken on purpose.)
	ResetTables ();
	{
		const u64 nBase = 512ULL * 1024 * 1024;		// second 512 MB slot
		// A range that starts and ends in the middle of a page, so that
		// both ends have to be rounded outwards.
		const int n = ClearPXNForRange (nBase + PageAddress (50) + 0x100,
						nBase + PageAddress (52) + 0x8);

		printf ("\n[7] el segundo bloque de 512 MB\n");
		Check (n == 3, "3 paginas cambiadas");
		Check ((s_L3B[50] & BitPXN) == 0, "las de la segunda tabla pierden PXN");
		Check ((s_L3B[52] & BitPXN) == 0, "hasta la ultima del rango");
		Check (PagesWithPXNA () == 8192, "la primera tabla no se toca entera");
	}

	// --- 8. canaries ----------------------------------------------------
	printf ("\n[8] nada escrito fuera de la tabla de nivel 3\n");
	{
		bool bBefore = true, bAfter = true;
		for (unsigned i = 0; i < 16; i++)
		{
			if (s_Canary_Before[i] != 0xAAAAAAAAAAAAAAAAULL) bBefore = false;
			if (s_Canary_After[i]  != 0xBBBBBBBBBBBBBBBBULL) bAfter = false;
		}
		Check (bBefore, "canario de antes intacto");
		Check (bAfter, "canario de despues intacto");
	}

	printf ("\n%d comprobaciones, %d fallos\n", s_nChecks, s_nFailures);

	return s_nFailures == 0 ? 0 : 1;
}
'''

OUT.write_text(HEAD + block + TAIL, encoding="utf-8")
print(f"gen-dynarec: {OUT.relative_to(ROOT)} regenerado ({len(block)} bytes de codigo real)")

# ---------------------------------------------------------------------------
# The same block, as an include, for the test about crossing a 512 MB boundary
# ---------------------------------------------------------------------------
# dynarec_cross_test.cpp builds two adjacent first-level blocks and a range that
# spans them, which is what an 8 MB malloc() near the top of a block looks like.
# Only the walk is reused - the constants, the logger stub and the register read
# are the test's own, so the two tests do not share a fake that could make both
# of them wrong in the same way.
CROSS = ROOT / "scripts/hostcheck/dynarec_cross.inc"

CROSS_HEAD = r'''// GENERATED by scripts/hostcheck/gen-dynarec.py - do not edit.
//
// The page-table walk from bare_dynarec.cpp, verbatim, for
// dynarec_cross_test.cpp.  The test supplies the constants, the logger and the
// TTBR0 read; this file is only the code under test.
'''

CROSS.write_text(CROSS_HEAD + block, encoding="utf-8")
print(f"gen-dynarec: {CROSS.relative_to(ROOT)} regenerado ({len(block)} bytes de codigo real)")
