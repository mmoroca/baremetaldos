#!/usr/bin/env python3
#
# Build scripts/hostcheck/scaling_test.cpp from the real scaling code in
# bare_video.cpp, for the same reason.
#
# Usage:
#   make check-scaling           # part of make check-host
#
"""
gen-scaling.py - build scripts/hostcheck/scaling_test.cpp from the real code.

The scaling arithmetic in bare_video.cpp is the kind of thing that is easy to
get subtly wrong (aspect applied twice, a clamp on one axis only) and that
shows up only as "the picture looks stretched" three builds later.  So the block
that decides the destination rectangle is copied here *verbatim*, between two
markers, and compiled with a table of modes and sources.

The copying is the point: no second implementation, no drift.  If the block in
bare_video.cpp changes and this file is not regenerated, the test keeps passing
while testing the old code - so the generator is run by the same make target
that runs the test.

    make check-scaling
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "src/platform/bare_video.cpp"
OUT = ROOT / "scripts/hostcheck/scaling_test.cpp"

text = SRC.read_text(encoding="utf-8")

# The block now begins with the reserved strip at the bottom (the line slots
# live there), so the extraction starts one step earlier: the strip is part
# of the geometry and the test has to see it, or it would be checking a
# layout that no longer exists.
START = "\tconst unsigned nSlotHeight = s_Font.GetCharHeight () + 2;"
END = "\ts_nDstX = (s_nModeWidth - s_nDstWidth) / 2;"

try:
    i = text.index(START)
    j = text.index(END)
except ValueError:
    sys.exit("gen-scaling: no encuentro los marcadores en bare_video.cpp "
             "(¿se ha movido el bloque de ComputeDestination?)")

block = text[i:j]

HEAD = r'''// GENERATED by scripts/hostcheck/gen-scaling.py - do not edit.
//
// The destination-rectangle arithmetic of bare_video.cpp, copied verbatim, run
// against every mode the port can ask the firmware for and every source size
// DOSBox produces.  Two things are checked, and both were wrong before:
//
//   * the aspect ratio of the result is 4:3 (1.30 - 1.37), for every pair;
//   * the picture occupies at least 70 % of the screen, i.e. the scaling rule
//     is not wasting half the panel to keep an integer multiple.
#include <cstdio>

typedef bool boolean;
#define FALSE false
#define TRUE  true

// Stand-ins for the two members the extracted block reads: the font metrics
// (one character line plus a pixel of padding) and the number of line slots,
// which is what decides how many rows the picture may not use.
struct TFontStandIn
{
	unsigned GetCharHeight (void) const { return 16; }
};
static TFontStandIn s_Font;
static constexpr unsigned MaxSlots = 2;

static unsigned s_nModeWidth, s_nModeHeight;
static unsigned s_nDstWidth, s_nDstHeight, s_nDstX, s_nDstY;
static unsigned s_nCoreAspectX, s_nCoreAspectY;
static boolean s_bAspectFromCore;

static unsigned MaxIntegerScale (unsigned nSrcWidth, unsigned nSrcHeight,
                                 unsigned nYStretchNum, unsigned nYStretchDen)
{
	const unsigned nEffHeight = nSrcHeight * nYStretchNum / nYStretchDen;
	unsigned nScaleX = s_nModeWidth / nSrcWidth;
	unsigned nScaleY = nEffHeight ? s_nModeHeight / nEffHeight : 0;
	unsigned nScale = nScaleX < nScaleY ? nScaleX : nScaleY;
	return nScale ? nScale : 1;
}

void ComputeDestination (unsigned nSrcWidth, unsigned nSrcHeight)
{
	const boolean bStretch = (nSrcHeight == 200 || nSrcHeight == 400)
				 && !s_bAspectFromCore;
	const unsigned nStretchNum = bStretch ? 6 : 5;
	const unsigned nStretchDen = bStretch ? 5 : 5;
'''

TAIL = r'''	s_nDstX = (s_nModeWidth - s_nDstWidth) / 2;
	s_nDstY = (s_nModeHeight - s_nDstHeight) / 2;
}

int main ()
{
	struct { unsigned w, h; const char *n; } modos[] = {
		{ 1920, 1080, "1920x1080" }, { 1280, 720, "1280x720" },
		{ 1024, 768, "1024x768" },   { 800, 600, "800x600" },
		{ 640, 480, "640x480" },
	};
	struct { unsigned w, h; const char *n; } fuentes[] = {
		{ 320, 200, "320x200" }, { 640, 400, "640x400" },
		{ 640, 480, "640x480" }, { 720, 400, "720x400" },
		{ 320, 240, "320x240" }, { 800, 600, "800x600" },
	};

	int nBadAspect = 0, nTooSmall = 0;

	s_bAspectFromCore = FALSE;

	for (unsigned m = 0; m < sizeof modos / sizeof modos[0]; m++)
	{
		printf ("\n--- modo %s\n", modos[m].n);

		for (unsigned f = 0; f < sizeof fuentes / sizeof fuentes[0]; f++)
		{
			s_nModeWidth = modos[m].w;
			s_nModeHeight = modos[m].h;
			ComputeDestination (fuentes[f].w, fuentes[f].h);

			const double fAspect = (double) s_nDstWidth / s_nDstHeight;

			// Measured against the area the picture is *allowed* to use,
			// not against the whole mode: as of .57 the bottom strip of
			// the display belongs to the port's own line slots (the panel
			// and the core's messages) and the emulator must not draw
			// there - that is what stops the panel flickering.  Two slots
			// of (char height + 2) are reserved: 36 rows, every mode.
			const unsigned nUsableH = s_nModeHeight - 2 * 18;
			const double fFill = 100.0 * s_nDstWidth * s_nDstHeight
					     / ((double) s_nModeWidth * nUsableH);

			const char *pNote = "";
			if (fAspect < 1.30 || fAspect > 1.37)
			{
				pNote = "   <-- ASPECTO FUERA DE 4:3";
				nBadAspect++;
			}
			else if (fFill < 70.0)
			{
				pNote = "   <-- desaprovecha la pantalla";
				nTooSmall++;
			}

			printf ("  %-9s -> %4ux%-4u  AR %.3f  ocupa %5.1f%%  en %u,%u%s\n",
				fuentes[f].n, s_nDstWidth, s_nDstHeight, fAspect,
				fFill, s_nDstX, s_nDstY, pNote);
		}
	}

	printf ("\naspecto fuera de 4:3: %d   casos por debajo del 70%%: %d\n",
		nBadAspect, nTooSmall);
	printf ("%s\n", nBadAspect == 0 ? "TODOS LOS MODOS A 4:3"
					: "HAY MODOS FUERA DE 4:3");

	return nBadAspect == 0 ? 0 : 1;
}
'''

OUT.write_text(HEAD + block + TAIL, encoding="utf-8")
print(f"gen-scaling: {OUT.relative_to(ROOT)} regenerado ({len(block)} bytes de codigo real)")
